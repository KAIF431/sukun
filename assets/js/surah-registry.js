// Hadith-Compliant Hasanat (Neki) Calculator (Jami' at-Tirmidhi 2910)
function calculateArabicHasanat(arabicText) {
  if (!arabicText) return 0;
  const lettersOnly = arabicText.replace(/[^\u0621-\u064A]/g, "");
  return lettersOnly.length * 10;
}
